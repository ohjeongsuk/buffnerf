CREATE TABLE game (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    source      VARCHAR(20)  NOT NULL,          -- LOL / STEAM
    external_id VARCHAR(50)                     -- Steam appid
);

CREATE TABLE patch (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id        BIGINT       NOT NULL REFERENCES game (id),
    version        VARCHAR(100) NOT NULL,
    title          VARCHAR(300),
    published_at   TIMESTAMPTZ,
    raw_content    TEXT,
    content_source VARCHAR(20),                 -- CRAWLED / MANUAL
    content_status VARCHAR(20)  NOT NULL,       -- READY / PENDING_CONTENT
    content_error  TEXT,
    summary_ko     TEXT,
    is_patch_note  BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (game_id, version)
);

CREATE TABLE balance_change (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch_id       BIGINT       NOT NULL REFERENCES patch (id) ON DELETE CASCADE,
    character_name VARCHAR(100) NOT NULL,       -- 정규화된 키 (롤: Data Dragon 영문 ID)
    attribute      VARCHAR(200) NOT NULL,
    change_type    VARCHAR(20)  NOT NULL,       -- BUFF / NERF / ADJUST
    before_value   VARCHAR(200),
    after_value    VARCHAR(200),
    evidence       TEXT,
    source         VARCHAR(20)  NOT NULL        -- AI / DIFF
);
CREATE INDEX idx_balance_change_patch ON balance_change (patch_id);
CREATE INDEX idx_balance_change_character ON balance_change (character_name);

CREATE TABLE ai_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch_id       BIGINT       NOT NULL REFERENCES patch (id) ON DELETE CASCADE,
    task           VARCHAR(20)  NOT NULL,       -- SUMMARY / EXTRACT / CLASSIFY
    model          VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(50)  NOT NULL,
    input_tokens   INTEGER,
    output_tokens  INTEGER,
    status         VARCHAR(20)  NOT NULL,       -- SUCCESS / FAILED
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- 같은 패치·같은 promptVersion으로 성공한 호출은 한 번만 (실패는 재시도 허용)
CREATE UNIQUE INDEX uq_ai_run_success ON ai_run (patch_id, task, prompt_version) WHERE status = 'SUCCESS';

